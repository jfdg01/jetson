#!/usr/bin/env python3
"""P6.2-DELIVERY proof deliverables (reproducible from runs/p62_delivery/).

Two committed artifacts:
  proof/p62_follow_pass.png        -- per-scenario FOLLOW-PASS bars (NUMBERS proof;
                                      regenerated by score_p62.py --overlay, copied here)
  proof/p62_warm_vs_cold.png       -- behavioural contact sheet: WARM (row 1) locks and
                                      holds the designated target while COLD (row 2) lands
                                      stale/off-frame, across the SAME flight timeline.

Run:  .venv-ft/bin/python experiments/2026-07-23-p62-delivery/make_proof.py
"""
from pathlib import Path
import json
import shutil
import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
RUNS = ROOT / "runs" / "p62_delivery"
PROOF = Path(__file__).resolve().parent / "proof"
SCEN = "seed00_r0"          # clean exemplar: WARM 1.0 coverage, COLD 0.0 (stale, off-target)
FRAMES = [100, 200, 399]    # acquire-window -> mid-follow -> end
# unambiguous legend (redrawn from CLEAN frames + rows.json, not the flight overlays whose
# GT-green and pred-green collide): GT=yellow, locked track=green, stale/off-target track=red.
GT_COL, LOCK_COL, MISS_COL = (255, 210, 0), (0, 220, 0), (235, 40, 40)


def _font(sz):
    try:
        return ImageFont.truetype("DejaVuSans-Bold.ttf", sz)
    except OSError:
        return ImageFont.load_default()


def _not_dead(im: Image.Image, tag: str):
    """look-at-it mechanical check: a >99%-single-colour frame is a failed render."""
    a = np.asarray(im.convert("RGB")).reshape(-1, 3)
    q = (a >> 3).astype(np.int32)
    keys = (q[:, 0] << 10) | (q[:, 1] << 5) | q[:, 2]
    frac = np.bincount(keys).max() / len(keys)
    assert frac < 0.99, f"{tag}: {frac:.3f} one colour -> failed render, not a proof"


def _cell(arm, fr, row):
    """clean frame + yellow GT + green/red track, captioned from rows.json."""
    im = Image.open(RUNS / f"{arm}_{SCEN}" / f"frame_{fr:05d}.png").convert("RGB")
    _not_dead(im, f"{arm} {fr}")
    d = ImageDraw.Draw(im)
    if row.get("gt"):
        d.rectangle(row["gt"], outline=GT_COL, width=3)
    tag = ""
    if row.get("deliver"):
        locked = row["lock_iou"] >= 0.25
        d.rectangle(row["deliver"], outline=LOCK_COL if locked else MISS_COL, width=2)
        tag = f"  iou={row['lock_iou']:.2f}"
    else:
        tag = "  NO DELIVERY (blind hover)"
    d.rectangle([0, 0, im.width, 26], fill=(0, 0, 0))
    d.text((5, 4), f"{arm.upper()}  frame {fr}{tag}", fill=(255, 255, 255), font=_font(18))
    return im


def contact_sheet():
    strips = []
    for arm in ("warm", "cold"):
        rows = {r["i"]: r for r in json.loads((RUNS / f"{arm}_{SCEN}" / "rows.json").read_text())}
        cells = [_cell(arm, fr, rows[fr]) for fr in FRAMES]
        strip = Image.new("RGB", (sum(c.width for c in cells), cells[0].height))
        x = 0
        for c in cells:
            strip.paste(c, (x, 0)); x += c.width
        strips.append(strip)
    W = max(s.width for s in strips)
    legend = Image.new("RGB", (W, 30), (255, 255, 255))
    ld = ImageDraw.Draw(legend)
    ld.text((6, 6), "yellow = designated target (GT)      green = track locked on target"
                    "      red = delivered track, stale/off-target", fill=(0, 0, 0), font=_font(16))
    sheet = Image.new("RGB", (W, 30 + sum(s.height for s in strips)), (255, 255, 255))
    sheet.paste(legend, (0, 0))
    y = 30
    for s in strips:
        sheet.paste(s, (0, y)); y += s.height
    out = PROOF / "p62_warm_vs_cold.png"
    sheet.save(out)
    return out


def main():
    PROOF.mkdir(exist_ok=True)
    fig = RUNS / "p62_follow_pass.png"
    if fig.exists():
        shutil.copy(fig, PROOF / "p62_follow_pass.png")
    out = contact_sheet()
    print(f"wrote {out}")
    print(f"wrote {PROOF / 'p62_follow_pass.png'}")


if __name__ == "__main__":
    main()
